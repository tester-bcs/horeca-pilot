//! Luck — вопрос §4.2 из MARKER_V0_RUST.md: «Кто владеет branch_id при
//! конкурентном порождении узлов?»
//! Ветка: Rust-проход (Маркер В.0 -> возврат)
//!
//! `Scheduler::run` (scheduler.rs) однопоточен — там вопрос не мог
//! возникнуть по построению (см. докстринг там же). Здесь — отдельный,
//! МИНИМАЛЬНЫЙ протокол конкурентной вставки, изолированный от полного
//! планировщика (тот требует `&mut ModelBackend`/`&mut ToolRegistry`,
//! которые не тривиально сделать `Send`+`Sync` без переработки самого
//! планировщика — задача за пределами объёма одного вопроса). Отвечает
//! на вопрос о ГРАФЕ (ребро 6->1) конкретно, не о планировщике целиком.
//!
//! ВЫБРАННЫЙ ПРОТОКОЛ: весь `IntentGraph` — под ОДНИМ `Mutex`, крупная
//! блокировка. «Проверить, существует ли node_id» и «вставить» —
//! в ОДНОЙ критической секции (лок держится на весь `spawn_concurrent`,
//! не освобождается между проверкой и вставкой) — иначе классическая
//! TOCTOU-гонка: два актора проверяют «узла ещё нет», оба решают
//! вставлять, второй паникует на дубликате node_id или тихо
//! перезаписывает первого. Крупная блокировка это устраняет по
//! построению, а не проверкой постфактум.
//!
//! СЛЕДСТВИЕ ПРОТОКОЛА, НЕ ПРЕДПОЛАГАВШЕЕСЯ ДО РЕАЛИЗАЦИИ (это и есть
//! содержательный ответ на вопрос, не факт «мьютекс работает»): если два
//! актора НЕЗАВИСИМО порождают узел с ОДИНАКОВЫМ содержимым (в этом
//! прототипе — совпадающий `node_id`, генерация которого детерминирована
//! от содержимого, см. `MockBackend`), выигрывает тот, кто первым
//! захватит лок; branch_id ВТОРОГО актора нигде не сохраняется —
//! `Node.branch_id` это ОДНО значение, не множество. Это не баг
//! протокола, а предел модели данных, вскрытый только попыткой сделать
//! порождение конкурентным: branch_id отвечает на вопрос «кто первым
//! записал», а не «кто когда-либо независимо достиг этого узла».
//! `cache_key` при этом общий в любом случае (Ядро п.3) — вычисление не
//! дублируется и не портится, теряется только атрибуция проигравшего
//! актора. Если бы кто-то захотел трекать «кто ЕЩЁ достиг этого узла»,
//! `branch_id: String` пришлось бы менять на `branch_ids: BTreeSet<String>`
//! — это уже правка модели данных Среза 3, за пределами вопроса §4.2 как
//! такового (тот спрашивал про протокол вставки, не про модель узла).

use crate::parser::{Edge, EdgeType, IntentGraph, Node};
use std::sync::Mutex;

/// Вставляет `new_nodes` (уже распарсенный вывод SPAWN) в `graph` под
/// единственным `Mutex` на весь граф. Возвращает node_id УСПЕШНО
/// вставленных этим вызовом узлов (пустой Vec, если все уже существовали
/// — под чужим branch_id, вставленным раньше).
pub fn spawn_concurrent(
    graph: &Mutex<IntentGraph>,
    source_node_id: &str,
    new_nodes: Vec<Node>,
    branch_id: &str,
) -> Vec<String> {
    let mut g = graph.lock().expect("mutex не отравлен предыдущей паникой");
    let mut inserted = Vec::new();

    for mut node in new_nodes {
        node.branch_id = branch_id.to_string();
        if g.nodes.contains_key(&node.node_id) {
            continue;
        }
        let id = node.node_id.clone();
        if g.add_node(node).is_err() {
            continue;
        }
        g.add_edge(Edge {
            source: source_node_id.to_string(),
            target: id.clone(),
            edge_type: EdgeType::Seq,
            label: None,
        });
        inserted.push(id);
    }
    inserted
}
